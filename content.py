def _places_word(n: int) -> str:
    n = abs(n) % 100
    if 11 <= n <= 14:
        return "мест"
    last = n % 10
    if last == 1:
        return "место"
    if 2 <= last <= 4:
        return "места"
    return "мест"


def spots_left_text() -> str:
    return f"Осталось: {SPOTS_LEFT} {_places_word(SPOTS_LEFT)}🔥"

